"""
Build the ``(graph, φ)`` training table for a molecular concept adapter.

DeFoG's molecular representation is a vocabulary of atom and bond classes, and a molecule is encoded by it (and decoded
back) with a codec that may be lossy: with the nine neutral elements a formal charge is dropped, and stereochemistry
is never represented. So the memberships ``φ`` are recomputed here on the **round-tripped** SMILES, the exact molecule
each DeFoG graph represents, so that training and evaluation (which can only ever score decoded molecules) share one
convention. Molecules whose graph cannot be decoded back into a valid molecule are dropped: no self-consistent
condition exists for them. A vocabulary with charged classes (the Ames rung) is read strictly by
``defog_megan.molecules``, and then a charge it cannot express rejects the molecule instead of changing it.

The defaults are the ZINC logP rung (nine neutral elements, kekulized, 6 to 38 heavy atoms). For the Ames rung pass the
Ames bundle, its 12 atom classes and ``--DATASET_TYPE '"classification"'`` (see ``reproduce/``). The molecules
themselves are not shipped: ``--SOURCE_CSV`` names a table with a SMILES column.

Usage:
    python experiments/prepare_concept_dataset.py --SOURCE_CSV '"molecules.csv"' --__TESTING__ True
    python experiments/prepare_concept_dataset.py --SOURCE_CSV '"molecules.csv"'
"""
import os
import json
import time

import numpy as np
import pandas as pd
import torch
from rdkit import Chem, RDLogger
from rdkit.Chem import Descriptors
from pycomex.functional.experiment import Experiment
from pycomex.utils import file_namespace, folder_path

from defog_megan.concepts import ConceptSpace
from defog_megan.data import save_conditions
from defog_megan.molecules import (
    KEKULE_BONDS, NEUTRAL_KEK_ATOMS, build_encoders, mol_to_smiles, pyg_data_to_mol, smiles_to_pyg_data,
)
from defog_megan.zoo import zoo_path

RDLogger.DisableLog("rdApp.*")

# ============================================================================
# Parameters
# ============================================================================

# :param SOURCE_CSV: Table of molecules to build conditions for (required). It is used purely as a SMILES source
#       here -- any score columns are recomputed, not reused.
SOURCE_CSV: str = ""
SMILES_COLUMN: str = "smiles"

# :param MEGAN_CKPT / CLUSTERING_PATH / PROCESSING_PATH: the three artifacts that
#       jointly define the concept vocabulary. The processing module MUST be the
#       one the MEGAN model was trained with.
MEGAN_CKPT: str = zoo_path("zinc-logp", "megan/model.ckpt")
CLUSTERING_PATH: str = zoo_path("zinc-logp", "megan/clustering.clu")
PROCESSING_PATH: str = zoo_path("zinc-logp", "megan/process.py")

# :param scoring knobs: must match the concept-extraction run, otherwise φ means
#       something different from what the concept report shows.
FIDELITY_THRESHOLD: float = 0.75
DATASET_TYPE: str = "regression"
SCORE_METHOD: str = "knn"
SCORE_K: int = 5
SHARPEN: str = "sparsemax"
SHARPEN_TEMPERATURE: float = 0.5

# :param ATOM_TYPES: the frozen base's node-class order. Do NOT derive from data.
ATOM_TYPES: list = list(NEUTRAL_KEK_ATOMS)
BOND_TYPES: list = list(KEKULE_BONDS)

# :param RECOMPUTE_ON_ROUNDTRIP: when True (the default, and the whole point of
#       this experiment) φ is computed on the decoded neutral molecule rather than
#       on the original SMILES. Set False to score the original SMILES instead.
RECOMPUTE_ON_ROUNDTRIP: bool = True

# :param DROP_DISCONNECTED: skip molecules whose SMILES contains a ".", i.e. salts
#       and mixtures. Off by default because the zinc64k source table has none.
#       It matters for tables with salts (~10% of the rows of some): the concept
#       clustering was extracted with those excluded, so a salt has no meaningful
#       φ, and conditioning on one would train the adapter toward a region the
#       concept vocabulary does not describe.
#
#       Prefer KEEP_LARGEST_FRAGMENT: the counterion is not what the concept
#       describes -- the organic fragment is.
DROP_DISCONNECTED: bool = False

# :param KEEP_LARGEST_FRAGMENT: desalt rather than discard. Keeps the heaviest
#       fragment of a multi-fragment SMILES and drops the rest, so a sodium
#       carboxylate contributes its organic half instead of nothing. Takes
#       precedence over DROP_DISCONNECTED when both are set. φ is recomputed on
#       the surviving fragment, which is the molecule the adapter will be asked
#       to generate.
KEEP_LARGEST_FRAGMENT: bool = False

# :param MAX_NODES / MIN_NODES: keep only what the frozen base can represent
#       (0 = no limit). A graph outside the base's node-count support cannot be
#       generated by it, so training on one teaches the adapter a target it can
#       never hit. The ZINC base declares 6..38 (the charged Ames base needs no limit here).
MAX_NODES: int = 38
MIN_NODES: int = 6

# :param KEKULIZE: encode aromatic rings as alternating single/double bonds
#       instead of a dedicated AROMATIC bond class. REQUIRED for a base whose
#       vocabulary has no AROMATIC class (both bases of the paper), and desirable
#       regardless: the aromatic class does not carry hydrogen count, so a
#       pyrrole-type N is indistinguishable from a pyridine-type one and every
#       N-H heterocycle fails to decode.
KEKULIZE: bool = True

BATCH_SIZE: int = 512
LIMIT: int = 0            # 0 = all molecules

__DEBUG__: bool = False
__TESTING__: bool = False
# no desktop notification when a run ends: on a machine without a desktop session it fails with a (harmless) traceback
__NOTIFY__: bool = False


@Experiment(base_path=folder_path(__file__), namespace=file_namespace(__file__), glob=globals())
def experiment(e: Experiment) -> None:
    # MEGAN inference stays on CPU: upstream ``forward_graphs`` builds its own CPU
    # DataLoader and never moves batches to the model's device, so a model on CUDA
    # raises a device mismatch. The model is small and the pass is batched, so this
    # is not the bottleneck -- see the throughput logged below.
    if not e.SOURCE_CSV:
        raise ValueError("SOURCE_CSV is required: a table of molecules with a SMILES column")
    e.log("building concept-conditioning table (MEGAN inference on CPU)")

    space = ConceptSpace.from_paths(
        e.MEGAN_CKPT, e.CLUSTERING_PATH, e.PROCESSING_PATH,
        fidelity_threshold=e.FIDELITY_THRESHOLD, dataset_type=e.DATASET_TYPE,
        score_method=e.SCORE_METHOD, score_k=e.SCORE_K,
        sharpen=e.SHARPEN, sharpen_temperature=e.SHARPEN_TEMPERATURE,
    )
    e.log(f"concept space: {space.num_concepts} concepts over channels {space.channels}")
    e["concepts/spec"] = space.spec()
    e["concepts/table"] = space.concept_table()

    atom_encoder, atom_decoder, bond_encoder, bond_decoder = build_encoders(
        e.ATOM_TYPES, e.BOND_TYPES)

    df = pd.read_csv(e.SOURCE_CSV, usecols=[e.SMILES_COLUMN])
    if e.LIMIT:
        df = df.head(e.LIMIT)
    e.log(f"{len(df)} source molecules from {os.path.basename(e.SOURCE_CSV)}")

    # -- encode -> decode, keeping only self-consistent pairs -----------------
    originals, neutrals = [], []
    n_unencodable = n_undecodable = n_changed = 0
    n_disconnected = n_too_large = n_too_small = n_desalted = 0
    for smiles in df[e.SMILES_COLUMN]:
        if "." in smiles:
            if e.KEEP_LARGEST_FRAGMENT:
                # Heaviest, not longest: a long counterion SMILES can out-length
                # the fragment that actually carries the chemistry.
                parent = Chem.MolFromSmiles(smiles)
                if parent is None:
                    n_unencodable += 1
                    continue
                pieces = Chem.GetMolFrags(parent, asMols=True, sanitizeFrags=True)
                if not pieces:
                    n_unencodable += 1
                    continue
                smiles = Chem.MolToSmiles(
                    max(pieces, key=lambda m: Descriptors.MolWt(m)))
                n_desalted += 1
            elif e.DROP_DISCONNECTED:
                n_disconnected += 1
                continue
        if e.MAX_NODES or e.MIN_NODES:
            reference_mol = Chem.MolFromSmiles(smiles)
            if reference_mol is not None:
                n_atoms = reference_mol.GetNumAtoms()
                if e.MAX_NODES and n_atoms > e.MAX_NODES:
                    n_too_large += 1
                    continue
                if e.MIN_NODES and n_atoms < e.MIN_NODES:
                    n_too_small += 1
                    continue
        data = smiles_to_pyg_data(smiles, atom_encoder, bond_encoder,
                                  kekulize=e.KEKULIZE)
        if data is None:
            n_unencodable += 1
            continue
        mol = pyg_data_to_mol(data, atom_decoder, bond_decoder)
        decoded = mol_to_smiles(mol) if mol is not None else None
        if decoded is None or Chem.MolFromSmiles(decoded) is None:
            n_undecodable += 1
            continue
        reference = Chem.MolFromSmiles(smiles)
        if reference is not None and decoded != Chem.MolToSmiles(reference):
            n_changed += 1
        originals.append(smiles)
        neutrals.append(decoded)

    e.log(f"kept {len(neutrals)}  |  desalted {n_desalted}  disconnected {n_disconnected}"
          f"  too_large {n_too_large}  too_small {n_too_small}"
          f"  unencodable {n_unencodable}  undecodable {n_undecodable}"
          f"  |  of the kept, {n_changed} changed on round-trip")
    e["data/n_desalted"] = int(n_desalted)
    e["data/n_disconnected"] = int(n_disconnected)
    e["data/n_too_large"] = int(n_too_large)
    e["data/n_too_small"] = int(n_too_small)
    e["data/n_source"] = int(len(df))
    e["data/n_kept"] = int(len(neutrals))
    e["data/n_unencodable"] = int(n_unencodable)
    e["data/n_undecodable"] = int(n_undecodable)
    e["data/n_changed_on_roundtrip"] = int(n_changed)
    e["data/kekulize"] = bool(e.KEKULIZE)

    # -- score ---------------------------------------------------------------
    scored = neutrals if e.RECOMPUTE_ON_ROUNDTRIP else originals
    e.log(f"scoring {len(scored)} molecules "
          f"({'round-tripped' if e.RECOMPUTE_ON_ROUNDTRIP else 'original'} SMILES)...")
    phi = np.ones((len(scored), space.num_concepts))
    started = time.time()
    for start in range(0, len(scored), e.BATCH_SIZE):
        chunk = scored[start:start + e.BATCH_SIZE]
        phi[start:start + len(chunk)] = space.phi(chunk, batch_size=e.BATCH_SIZE)
        done = min(start + len(chunk), len(scored))
        if (start // e.BATCH_SIZE) % 20 == 0:
            rate = done / max(time.time() - started, 1e-9)
            eta = (len(scored) - done) / max(rate, 1e-9)
            e.log(f"  scored {done}/{len(scored)}  ({rate:.0f} mol/s, eta {eta / 60:.1f} min)")
    e["phi/scoring_seconds"] = float(time.time() - started)
    e.log(f"scoring took {time.time() - started:.1f}s "
          f"({len(scored) / max(time.time() - started, 1e-9):.0f} mol/s)")

    # -- report how informative the conditions actually are -------------------
    assigned = phi < 0.999
    per_molecule = assigned.sum(axis=1)
    e["phi/mean_assigned_per_molecule"] = float(per_molecule.mean())
    e["phi/frac_no_concept"] = float((per_molecule == 0).mean())
    e["phi/per_concept_support"] = {
        cid: int(assigned[:, i].sum()) for i, cid in enumerate(space.concept_ids)
    }
    e.log(f"φ: mean {per_molecule.mean():.2f} concepts assigned per molecule; "
          f"{(per_molecule == 0).mean():.1%} carry the no-concept condition")
    empty = [cid for i, cid in enumerate(space.concept_ids) if assigned[:, i].sum() == 0]
    if empty:
        e.log(f"WARNING {len(empty)} concepts have no support in this table: {empty}")

    # -- persist -------------------------------------------------------------
    # .npz, not parquet, so that reading the table needs no pyarrow (see defog_megan.data).
    table_path = save_conditions(
        os.path.join(e.path, "concept_conditions.npz"),
        smiles=neutrals, phi=phi, concept_ids=space.concept_ids,
        smiles_original=originals)
    e.log(f"wrote {table_path} ({len(neutrals)} rows x {space.num_concepts} concepts)")

    with open(os.path.join(e.path, "concept_spec.json"), "w") as file:
        json.dump({"spec": space.spec(), "table": space.concept_table(),
                   "recomputed_on_roundtrip": bool(e.RECOMPUTE_ON_ROUNDTRIP),
                   "megan_ckpt": os.path.basename(e.MEGAN_CKPT), "clustering": os.path.basename(e.CLUSTERING_PATH),
                   "processing": os.path.basename(e.PROCESSING_PATH)}, file, indent=2)
    e.log("Done.")


@experiment.testing
def testing(e: Experiment) -> None:
    e.LIMIT = 200
    e.BATCH_SIZE = 64


experiment.run_if_main()
